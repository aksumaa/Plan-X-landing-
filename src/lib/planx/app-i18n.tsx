export type AppDict = (typeof dicts)["en"];

const Ctx = createContext<{ lang: AppLang; setLang: (l: AppLang) => void; t: AppDict } | null>(null);

const KEY = "planx.app.lang";

export function AppLangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<AppLang>("uz");

  useEffect(() => {
    const stored = localStorage.getItem(KEY) as AppLang | null;
    if (stored && APP_LANGS.includes(stored)) setLangState(stored);
  }, []);

  const setLang = (l: AppLang) => {
    setLangState(l);
    localStorage.setItem(KEY, l);
  };

  const value = useMemo(() => ({ lang, setLang, t: dicts[lang] as AppDict }), [lang]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useT() {
  const ctx = useContext(Ctx);
  if (!ctx) throw new Error("useT must be used inside AppLangProvider");
  return ctx;
}
